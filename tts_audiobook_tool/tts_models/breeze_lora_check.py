"""Model-free check of a Breeze TTS 2 LoRA (Instavar format, see `breeze_lora`), for the voice
menu: run in the main process, torch-free, without loading the model or reading any of its files.

The adapter's own files are fully checked as the merge loader checks them (`breeze_lora_source`:
form, manifest or receipt, checksums, rank and alpha; then key layout, complete A/B pairs, float
dtypes), plus values (NaN/inf rejects; all-zero B factors warn). The app pins one Breeze base
revision, so what the loader compares against the loaded model and its files is compared against
tables of that revision instead (`breeze_lora_targets`, generated by
`testx/breeze_lora_targets_gen.py`):

- a manifest's pinned base files, against the revision's file checksums (`verify_base` reads the
  model directory instead);
- each target, against the revision's valid LoRA targets and their shapes: an untied linear layer
  whose weight is in the checkpoint (what `breeze_lora.plan_merge` and the switcher's restore
  check require of the loaded model).

Every run still prepares each voice's LoRA against the loaded model (`prepare_voice_loras`)
before generating, which is the authoritative check.
"""
from __future__ import annotations

from tts_audiobook_tool.app_types.model_target import ModelTarget
from tts_audiobook_tool.tts_models.breeze_lora_source import PAIR_SUFFIXES, BreezeAdapterSource, resolve_adapter
from tts_audiobook_tool.tts_models.breeze_lora_targets import BASE_FILE_SHA256, TARGET_FAMILIES
from tts_audiobook_tool.tts_models.lora_files import (
    LoraCheck, LoraLoadError, SafetensorsFile, TensorInfo, check_strength, check_values,
)


def target_shape(module_name: str) -> tuple[int, int] | None:
    """The weight shape (out, in) of a valid LoRA target of the pinned base, or None."""
    parts = module_name.split(".")
    indices = [i for i, part in enumerate(parts) if part.isascii() and part.isdigit()]
    if len(indices) > 1:
        return None
    index = 0
    if indices:
        text = parts[indices[0]]
        if text != str(int(text)):
            return None
        index = int(text)
        parts[indices[0]] = "#"
    family = TARGET_FAMILIES.get(".".join(parts))
    if family is None or index >= family[1]:
        return None
    return family[0]


def verify_pinned_base(source: BreezeAdapterSource) -> None:
    """A manifest's pinned base files against the app's pinned Breeze revision."""
    for name, expected in (source.base_files or {}).items():
        observed = BASE_FILE_SHA256.get(name.replace("\\", "/"))
        if observed is None:
            raise LoraLoadError(f"Base model file {name} isn't part of the Breeze TTS 2 model, "
                                "so the adapter's base can't be verified")
        if observed != expected:
            raise LoraLoadError(f"Adapter was trained on a different Breeze TTS 2 base ({name} differs)")


def check_adapter(target: ModelTarget, strength: float = 1.0) -> LoraCheck:
    """Checks an adapter without the model or its files (only the adapter's are read)."""
    try:
        check_strength(strength)
        source = resolve_adapter(target)
        if source.base_files:
            verify_pinned_base(source)
        return LoraCheck(warnings=tuple(check_weights(source)))
    except LoraLoadError as e:
        return LoraCheck(error=str(e))
    except Exception as e:
        return LoraCheck(error=f"Couldn't read adapter: {type(e).__name__}: {e}")


def check_weights(source: BreezeAdapterSource) -> list[str]:
    """Checks the adapter's tensors; raises `LoraLoadError`, else returns warnings."""
    file = SafetensorsFile(source.weights_path)
    rank = source.rank
    halves: dict[str, dict[str, tuple[str, TensorInfo]]] = {}
    for key, info in file.tensors.items():
        suffix = next((s for s in PAIR_SUFFIXES if key.endswith(s)), None)
        if suffix is None:
            raise LoraLoadError(f"Unsupported adapter tensor: {key} (expected Instavar .lora_A / .lora_B factors)")
        halves.setdefault(key.removesuffix(suffix), {})[PAIR_SUFFIXES[suffix]] = (key, info)

    b_keys = []
    for module_name, half in halves.items():
        if "A" not in half or "B" not in half:
            raise LoraLoadError(f"Incomplete LoRA pair for {module_name}")
        shape = target_shape(module_name)
        if shape is None:
            raise LoraLoadError(f"Adapter targets {module_name}, which isn't a layer of Breeze TTS 2 "
                                "that a LoRA can change")
        (_, a), (b_key, b) = half["A"], half["B"]
        if len(a.shape) != 2 or len(b.shape) != 2:
            raise LoraLoadError(f"LoRA factors for {module_name} are not matrices")
        out_features, in_features = shape
        if a.shape != (rank, in_features) or b.shape != (out_features, rank):
            raise LoraLoadError(
                f"Shape mismatch for {module_name}: A {a.shape}, B {b.shape}, model {shape}, r={rank}")
        if not a.is_float or not b.is_float:
            raise LoraLoadError(f"Non-float LoRA factors for {module_name}")
        b_keys.append(b_key)

    if not halves:
        raise LoraLoadError("Adapter has no tensors")
    return check_values(file, list(file.tensors), b_keys)
