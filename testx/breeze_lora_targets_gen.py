"""Regenerates `tts_audiobook_tool/tts_models/breeze_lora_targets.py` from the pinned Breeze TTS 2 base.

The voice menu checks Breeze LoRAs without loading the model or reading its files
(`breeze_lora_check`), against two tables of the pinned base (`BreezeBaseModel.HF_REVISION`):

- every valid LoRA target: an `nn.Linear` whose weight is in the checkpoint and not
  shared with another parameter (the rules `breeze_lora.plan_merge` and the switcher's
  restore check apply to the loaded model), with its weight shape;
- every file of the snapshot, with its sha256 (what an Instavar manifest pins).

The module tree is built on the meta device (no weights are read; the checkpoint headers
confirm each shape). Run it after bumping `HF_REVISION`; a unit test fails until then.

Run: ./venv-breeze/bin/python -m testx.breeze_lora_targets_gen
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import struct
from pathlib import Path

import torch
from huggingface_hub import snapshot_download
from transformers import AutoConfig

from breeze_tts.models.breeze import BreezeForConditionalGeneration  # type: ignore

from tts_audiobook_tool.tts_models.breeze_base_model import BreezeBaseModel

OUTPUT = Path(__file__).resolve().parent.parent / "tts_audiobook_tool" / "tts_models" / "breeze_lora_targets.py"
_SHA256 = re.compile(r"[0-9a-f]{64}")
_INDEX = re.compile(r"\.(\d+)\.")


def checkpoint_shapes(model_dir: Path) -> dict[str, tuple[int, ...]]:
    weight_map = json.loads((model_dir / "model.safetensors.index.json").read_text())["weight_map"]
    shapes: dict[str, tuple[int, ...]] = {}
    for file_name in sorted(set(weight_map.values())):
        with open(model_dir / file_name, "rb") as f:
            (length,) = struct.unpack("<Q", f.read(8))
            header = json.loads(f.read(length))
        header.pop("__metadata__", None)
        shapes.update({key: tuple(info["shape"]) for key, info in header.items()})
    return shapes


def target_families(model_dir: Path) -> dict[str, tuple[tuple[int, int], int]]:
    config = AutoConfig.from_pretrained(model_dir)
    with torch.device("meta"):
        model = BreezeForConditionalGeneration(config)
    model.tie_weights()
    # Meta tensors have no storage, so tied parameters are found by identity (they are one object)
    uses: dict[int, int] = {}
    for _, param in model.named_parameters(remove_duplicate=False):
        uses[id(param)] = uses.get(id(param), 0) + 1
    shapes = checkpoint_shapes(model_dir)

    indices: dict[str, tuple[tuple[int, int], set[int]]] = {}
    for name, module in model.named_modules():
        if not isinstance(module, torch.nn.Linear) or uses[id(module.weight)] > 1:
            continue
        shape = tuple(module.weight.shape)
        if shapes.get(f"{name}.weight") != shape:
            continue
        found = _INDEX.findall(f".{name}.")
        if len(found) > 1:
            raise SystemExit(f"Unsupported module name (more than one index): {name}")
        pattern = _INDEX.sub(".#.", f".{name}.")[1:-1]
        known_shape, seen = indices.setdefault(pattern, (shape, set()))  # type: ignore[arg-type]
        if known_shape != shape:
            raise SystemExit(f"Layers of {pattern} differ in shape: {known_shape} vs {shape}")
        seen.add(int(found[0]) if found else 0)

    result = {}
    for pattern, (shape, seen) in indices.items():
        if seen != set(range(len(seen))):
            raise SystemExit(f"Layer indices of {pattern} aren't contiguous from 0")
        result[pattern] = (shape, len(seen))
    return result


def file_hashes(model_dir: Path) -> dict[str, str]:
    """Snapshot files (as an Instavar manifest names them) -> sha256. hf names LFS blobs by
    their sha256 (other blobs by git sha1), as `breeze_lora.verify_base` relies on too."""
    result = {}
    for path in sorted(model_dir.rglob("*")):
        if not path.is_file():
            continue
        blob_name = os.path.basename(os.path.realpath(path))
        if _SHA256.fullmatch(blob_name):
            digest = blob_name
        else:
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
        result[path.relative_to(model_dir).as_posix()] = digest
    return result


def render(revision: str, hashes: dict[str, str], families: dict[str, tuple[tuple[int, int], int]]) -> str:
    lines = [
        '"""Generated by `testx/breeze_lora_targets_gen.py` from the pinned Breeze TTS 2 base; don\'t edit.',
        "",
        "Used by `breeze_lora_check` to check an adapter without the model or its files.",
        '"""',
        "",
        f'BASE_REVISION = "{revision}"',
        "",
        '# Snapshot file (relative, "/"-separated) -> sha256',
        "BASE_FILE_SHA256: dict[str, str] = {",
        *(f'    "{name}": "{digest}",' for name, digest in hashes.items()),
        "}",
        "",
        "# Every valid LoRA target (an untied linear layer whose weight is in the checkpoint):",
        '# module name, with "#" for a layer index (0 to count - 1) -> (weight shape (out, in), count)',
        "TARGET_FAMILIES: dict[str, tuple[tuple[int, int], int]] = {",
        *(f'    "{pattern}": (({shape[0]}, {shape[1]}), {count}),' for pattern, (shape, count) in families.items()),
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    revision = BreezeBaseModel.HF_REVISION
    model_dir = Path(snapshot_download(BreezeBaseModel.HF_REPO_ID, revision=revision))
    families = target_families(model_dir)
    hashes = file_hashes(model_dir)
    OUTPUT.write_text(render(revision, hashes, families), encoding="utf-8")
    total = sum(count for _, count in families.values())
    print(f"Wrote {OUTPUT}: {len(families)} target families ({total} modules), {len(hashes)} base files")


if __name__ == "__main__":
    main()
